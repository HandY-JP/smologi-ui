/** サブセットBで符号化できる最小/最大の文字コード（ASCII 32〜126）。 */
const CODE128B_MIN_CHAR_CODE = 0x20;
const CODE128B_MAX_CHAR_CODE = 0x7e;

/** 1文字をサブセットBの値（0〜94）に変換する。範囲外は例外。 */
export function code128BCharValue(char: string): number {
  const code = char.charCodeAt(0);
  if (code < CODE128B_MIN_CHAR_CODE || code > CODE128B_MAX_CHAR_CODE) {
    throw new Error(`Code128B で符号化できない文字です: ${JSON.stringify(char)}`);
  }
  return code - CODE128B_MIN_CHAR_CODE;
}

/** 文字列がそのまま Code128 サブセットBで符号化できるか（ASCII 32〜126のみ）。 */
export function isCode128BEncodable(text: string): boolean {
  if (!text) return false;
  return Array.from(text).every((char) => {
    const code = char.charCodeAt(0);
    return code >= CODE128B_MIN_CHAR_CODE && code <= CODE128B_MAX_CHAR_CODE;
  });
}

/**
 * START B + データ + チェックサム + STOP の値配列を返す。
 * チェックサムは mod 103（START値を重み1として、以降の文字は位置番号を重みにする標準式）。
 */
export function code128BEncodeValues(text: string): number[] {
  const dataValues = Array.from(text).map(code128BCharValue);
  const values = [CODE128_START_B, ...dataValues];
  let checksum = values[0];
  for (let i = 1; i < values.length; i++) {
    checksum += values[i] * i;
  }
  checksum %= 103;
  return [...values, checksum, CODE128_STOP];
}

/** 値配列 → 幅パターン（モジュール数の配列。バー/スペース交互、バーから開始）へ展開する。 */
export function code128Widths(values: number[]): number[] {
  return values.flatMap((value) => {
    const pattern = CODE128_PATTERNS[value];
    if (!pattern) throw new Error(`未定義の Code128 値です: ${value}`);
    return pattern;
  });
}

export type Code128Bar = {
  /** 左端からのオフセット（モジュール単位）。 */
  x: number;
  /** バーの幅（モジュール単位）。 */
  width: number;
};

/**
 * 文字列から「黒バーの位置と幅（モジュール単位）」の配列を返す。
 * 白スペースは描画不要なので除外し、react-pdf の Rect 列挙をそのまま作れる形にする。
 */
export function code128Bars(text: string): { bars: Code128Bar[]; totalModules: number } {
  const widths = code128Widths(code128BEncodeValues(text));
  const bars: Code128Bar[] = [];
  let x = 0;
  let isBar = true;
  for (const width of widths) {
    if (isBar) bars.push({ x, width });
    x += width;
    isBar = !isBar;
  }
  return { bars, totalModules: x };
}
